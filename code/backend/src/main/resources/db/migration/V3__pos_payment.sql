-- Tổng tiền hoá đơn và thông tin thanh toán (tiền mặt / chuyển khoản VietQR).
ALTER TABLE invoices ADD COLUMN total NUMERIC(19,2) NOT NULL DEFAULT 0 CHECK (total >= 0);
ALTER TABLE invoices ADD COLUMN paid_at TIMESTAMP WITH TIME ZONE;

CREATE TABLE payments (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    invoice_id BIGINT NOT NULL UNIQUE REFERENCES invoices(id),
    method VARCHAR(20) NOT NULL CHECK (method IN ('CASH', 'TRANSFER')),
    amount NUMERIC(19,2) NOT NULL CHECK (amount >= 0),
    received NUMERIC(19,2) NOT NULL CHECK (received >= 0),
    change_amount NUMERIC(19,2) NOT NULL DEFAULT 0 CHECK (change_amount >= 0),
    transfer_ref VARCHAR(64),
    created_at TIMESTAMP WITH TIME ZONE NOT NULL
);

CREATE INDEX idx_invoice_paid_at ON invoices(paid_at);

