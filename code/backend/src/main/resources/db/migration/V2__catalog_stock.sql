-- Danh mục, nhà cung cấp, phiếu nhập và ngưỡng cảnh báo tồn kho.
CREATE TABLE categories (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(120) NOT NULL UNIQUE
);

ALTER TABLE products ADD COLUMN category_id BIGINT REFERENCES categories(id);
ALTER TABLE products ADD COLUMN image_url VARCHAR(500);
ALTER TABLE products ADD COLUMN active BOOLEAN NOT NULL DEFAULT TRUE;

CREATE TABLE suppliers (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(160) NOT NULL,
    phone VARCHAR(32),
    address VARCHAR(300)
);

ALTER TABLE inventory ADD COLUMN min_quantity INTEGER NOT NULL DEFAULT 10 CHECK (min_quantity >= 0);

CREATE TABLE import_receipts (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    supplier_id BIGINT REFERENCES suppliers(id),
    warehouse_id BIGINT NOT NULL REFERENCES warehouses(id),
    employee_id BIGINT NOT NULL REFERENCES employees(id),
    created_at TIMESTAMP WITH TIME ZONE NOT NULL,
    note VARCHAR(500),
    total NUMERIC(19,2) NOT NULL DEFAULT 0 CHECK (total >= 0)
);

CREATE TABLE import_lines (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    receipt_id BIGINT NOT NULL REFERENCES import_receipts(id),
    sku_id BIGINT NOT NULL REFERENCES skus(id),
    quantity INTEGER NOT NULL CHECK (quantity > 0),
    unit_cost NUMERIC(19,2) NOT NULL CHECK (unit_cost >= 0)
);

CREATE INDEX idx_product_category ON products(category_id);
CREATE INDEX idx_import_line_receipt ON import_lines(receipt_id);
CREATE INDEX idx_import_line_sku ON import_lines(sku_id);

